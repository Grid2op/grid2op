import unittest
import warnings
from unittest import mock

import numpy as np

import grid2op
from grid2op.Agent import DoNothingAgent
from grid2op.utils import ScoreL2RPN2020


class Issue792Tester(unittest.TestCase):
    """The 100 points anchor of the L2RPN 2020 score is the losses of the reference agent
    times `min_losses_ratio`: the losses are its production minus its load, not its load
    minus its load."""

    def setUp(self) -> None:
        self.max_iter = 10
        self.nb_scenario = 2
        with warnings.catch_warnings():
            warnings.filterwarnings("ignore")
            self.env = grid2op.make("l2rpn_case14_sandbox", test=True, _add_to_name=type(self).__name__)
        self.scorer = ScoreL2RPN2020(
            self.env,
            max_step=self.max_iter,
            nb_scenario=self.nb_scenario,
            env_seeds=[0 for _ in range(self.nb_scenario)],
            agent_seeds=[0 for _ in range(self.nb_scenario)],
        )
        return super().setUp()

    def tearDown(self) -> None:
        self.scorer.clear_all()
        self.env.close()
        return super().tearDown()

    def _expected_best_anchors(self):
        stat = self.scorer.stat_no_overflow_rp
        load_p, ids = stat.get("load_p")
        gen_p, _ = stat.get("gen_p")
        ids = ids.reshape(-1)
        res = []
        for ep_id in range(self.nb_scenario):
            # the first observation is generated by the environment and does not count
            ep_loads = load_p[ids == ep_id, :].sum(axis=1)[1:][: self.max_iter]
            ep_gens = gen_p[ids == ep_id, :].sum(axis=1)[1:][: self.max_iter]
            res.append((ep_gens - ep_loads).sum() * self.scorer.min_losses_ratio)
        return res

    def test_best_anchor_is_the_losses(self):
        anchors = []
        real_interp = np.interp

        def interp(x, xp, fp, *args, **kwargs):
            anchors.append(xp[0])
            return real_interp(x, xp, fp, *args, **kwargs)

        agent = DoNothingAgent(self.env.action_space)
        with mock.patch("grid2op.utils.l2rpn_2020_scores.np.interp", side_effect=interp):
            self.scorer.get(agent)
        expected = self._expected_best_anchors()
        assert len(anchors) == self.nb_scenario, f"{len(anchors)} episodes scored"
        for got, exp in zip(anchors, expected):
            assert exp > 0.0, "the reference agent should have some losses"
            assert np.abs(got - exp) <= 1e-3 * exp, f"best anchor {got} vs losses {exp}"


if __name__ == "__main__":
    unittest.main()
